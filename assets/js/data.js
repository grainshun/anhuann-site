/* =========================================================
 * Anhuann · 内容配置文件（data.js）
 * ---------------------------------------------------------
 * 这是整个网站唯一需要日常维护的文件。
 *
 * 它只做一件事：把网站要展示的所有文字内容，定义成几个
 * 全局常量（SITE / ABOUT / POSTS / SOCIALS / UI），供 main.js 读取并渲染。
 *
 * 你（站长）平时改网站，只需要改这个文件：
 *   - 改完保存，刷新浏览器即可生效（前台会实时从服务器读取）；
 *   - 后台 admin.html 保存时，服务器也是把这个对象序列化回写本文件。
 *
 * 不需要动 index.html / style.css / main.js，除非你要改结构或样式。
 *
 * ─────────────────────────────────────────────
 * 快速上手（三步）
 * ─────────────────────────────────────────────
 *   1. 改标题/文章/社交：直接改下面数组里的文字，保存。
 *   2. 想加一篇新文章：复制下面 POSTS 里任意一个 { ... } 对象，
 *      粘到数组末尾，改 title/date/tags/excerpt/body 即可。
 *   3. 想加一个社交账号：复制 SOCIALS 里任意一个 { ... } 对象，
 *      粘到末尾，按注释改字段即可。
 *
 * ─────────────────────────────────────────────
 * 通用规则（很重要，先看这里）
 * ─────────────────────────────────────────────
 *   - 这里是「JavaScript 源码」，不是 JSON：
 *       · 字符串用英文双引号 "..." 包起来；
 *       · 字段之间用英文逗号 , 分隔（最后一项后面不要逗号）；
 *       · 注释用 // 或块注释，不影响运行。
 *     写错了常见症状：页面空白/控制台报错。
 *     可用 node --check assets/js/data.js 自检语法。
 *
 *   - 字符串里想换行：写 \n（例如 "第一行\n第二行"）。
 *
 *   - 字符串里如果带 HTML 标签（如 <h3>、<strong>），会被原样渲染；
 *     普通文本会被自动转义，所以你在正文里写 <b> 这类标签不会生效，
 *     只有 body 数组中「以 < 开头」的元素才会按 HTML 原样插入。
 *
 *   - 正文（body）是「字符串数组」，每个元素是一段；
 *     首字符为 "<" 的行会被当作 HTML 直接插入（用于小标题、列表、引用等）。
 *
 *   - 支持 LaTeX 公式（由本地 KaTeX 渲染，离线可用）：
 *       行内公式  $E=mc^2$
 *       块级公式  $$\int_0^1 x^2\,dx = \frac{1}{3}$$
 *     也支持 \( ... \) 和 \[ ... \] 写法。
 *     注意：$ 会被当作公式起始符，若要显示美元金额请写成 \$5。
 *
 *   - 单引号 ' 和双引号 " 如果出现在中文文案里没问题；
 *     但如果出现在用双引号包裹的字符串内部，请写成 \" 转义，
 *     否则会提前结束字符串。
 * ========================================================= */

